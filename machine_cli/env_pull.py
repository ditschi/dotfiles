GENERATED_HEADER = "# generated by machine env pull — do not commit"
LOCAL_ONLY_HEADER = (
    "# --- local only: not in Bitwarden (resolve with machine attention) ---"
)
ASSIGNMENT = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=")
SECTION = re.compile(r"^# --- (.+) ---$")
# Marks a carried-over key that a Bitwarden item set before, so its origin survives.
WAS_IN = re.compile(r"^# was in (\S+)$")
# Section of a line: None before any section, LOCAL_ONLY, or the Bitwarden item name.
LOCAL_ONLY = "local only"

TO_BITWARDEN = "bitwarden"
KEEP_LOCALLY = "local"
REMOVE = "remove"
SKIP = "skip"
PUSH = "push"
DISCARD = "discard"
# Results of pushing one env file (machine env push).
PUSHED = "pushed"
NOTHING_TO_PUSH = "nothing"
DECLINED = "declined"
FAILED = "failed"

# A value that names another Bitwarden item: {{bw:<item name>/<target>}}.
REFERENCE = re.compile(r"^\{\{bw:(.+)/(password|username|field:[^/]+)\}\}$")
# Stands for a resolved value until the file's format is known (see render_env).
REF_TOKEN = re.compile(r"@@machine-ref:\d+@@")
EXPORT = re.compile(r"^\s*export\s+")
SYNTAX_HINT = [
    "# A value may reference another Bitwarden item instead of a copy:",
    "#   KEY={{bw:<item name>/password}}   (or /username, /field:<NAME>)",
    "# Edit this file and run `machine env push` to write changes to Bitwarden.",
]


def assignment_parts(line: str) -> Tuple[str, str, str]:
    """(prefix up to and including '=', key, raw value) of an assignment line."""
    match = ASSIGNMENT.match(line)
    assert match
    end = match.end()
    return line[:end], match.group(1), line[end:]


def unquoted(raw: str) -> str:
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "'\"":
        return raw[1:-1]
    return raw


def parse_reference(raw: str) -> Optional[Tuple[str, str]]:
    """(item name, target) when a raw value is a reference."""
    match = REFERENCE.match(unquoted(raw))
    return (match.group(1), match.group(2)) if match else None


def reference_value(item: dict, target: str) -> Optional[str]:
    login = item.get("login") or {}
    if target in ("password", "username"):
        value = login.get(target)
    else:
        name = target.removeprefix("field:")
        value = next(
            (f.get("value") for f in item.get("fields") or [] if f.get("name") == name),
            None,
        )
    return None if value in (None, "") else str(value)


def line_value(line: str, sourced: bool) -> str:
    """The value the shell loader sets for an assignment line."""
    raw = assignment_parts(line)[2]
    if not sourced:
        return raw
    try:
        return " ".join(shlex.split(raw, comments=True))
    except ValueError:
        return raw


def item_lines(parsed: "EnvFile") -> Dict[str, str]:
    """Key -> last line of the keys that a Bitwarden section of a generated file sets."""
    return {
        key: line
        for key, line, section in parsed.assignments
        if section not in (None, LOCAL_ONLY) and key not in parsed.local_only
    }


def same_line(a: Optional[str], b: Optional[str]) -> bool:
    if a is None or b is None:
        return a is b
    return a.strip() == b.strip()


def is_sourced(text: str) -> bool:
    """Like the shell loader: a file with an export line is sourced, else parsed."""
    return any(
        EXPORT.match(line) for line in text.splitlines() if not line.startswith("#")
    )


@dataclass
class EnvFile:
    """An existing ~/.env or ~/.env.host, split by where each line came from."""

    generated: bool
    lines: List[Tuple[str, Optional[str]]]  # (line, section)
    assignments: List[Tuple[str, str, Optional[str]]]  # (key, line, section)
    shell_code: List[str]
    local_only: List[str]  # keys written in the local-only section

    def keys(self) -> set:
        return {key for key, _line, _section in self.assignments}


def parse_env_file(text: str) -> EnvFile:
    generated = text.startswith(GENERATED_HEADER)
    # The loader reads a file without export lines as plain KEY=value, not as shell.
    sourced = is_sourced(text)
    section: Optional[str] = None
    was_in: Optional[str] = None
    lines: List[Tuple[str, Optional[str]]] = []
    assignments: List[Tuple[str, str, Optional[str]]] = []
    shell_code: List[str] = []
    local_only: List[str] = []
    for line in text.splitlines():
        if line == LOCAL_ONLY_HEADER:
            section = LOCAL_ONLY
        elif generated and (match := SECTION.match(line)):
            section = match.group(1)
        lines.append((line, section))
        if section == LOCAL_ONLY and (match := WAS_IN.match(line)):
            was_in = match.group(1)
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        match = ASSIGNMENT.match(line)
        try:
            parsable = bool(match) and (
                not sourced or bool(shlex.split(line, comments=True))
            )
        except ValueError:
            parsable = False
        if parsable:
            assignments.append((match.group(1), line, was_in or section))
            if section == LOCAL_ONLY:
                local_only.append(match.group(1))
            was_in = None
        else:
            shell_code.append(line)
    return EnvFile(generated, lines, assignments, shell_code, local_only)


@dataclass
class LocalOnly:
    """Content of one existing env file that no Bitwarden item or ~/.env.local sets."""

    path: Path
    item: str
    keys: Dict[str, List[str]] = field(default_factory=dict)  # key -> original lines
    # key -> Bitwarden item that set it before (deleted in the vault since)
    was_in: Dict[str, str] = field(default_factory=dict)
    shell_code: List[str] = field(default_factory=list)
    keep_lines: List[str] = field(default_factory=list)  # kept locally for shell code


def local_only_content(
    path: Path, item: str, existing: EnvFile, generated: str, sourced: set
) -> LocalOnly:
    """Keys of `existing` outside `sourced`, and shell code that `generated` lacks."""
    result = LocalOnly(path, item)
    local = set()
    for key, line, section in existing.assignments:
        if key in sourced:
            continue
        result.keys.setdefault(key, []).append(line)
        if existing.generated and section not in (None, LOCAL_ONLY):
            result.was_in.setdefault(key, section)
        else:
            local.add(key)
    for key in local:
        result.was_in.pop(key, None)
    new_lines = set(generated.splitlines())
    result.shell_code = [line for line in existing.shell_code if line not in new_lines]
    if result.shell_code:
        result.keep_lines = [
            line
            for line, section in existing.lines
            if not existing.generated
            or (section == LOCAL_ONLY and not line.startswith("# "))
            or (section is None and line.strip() and not line.startswith("#"))
        ]
    return result


class EnvPullMixin:
    def display(self, path: Path) -> str:
        if not path.is_relative_to(self.home):
            return str(path)
        return f"~/{path.relative_to(self.home)}"

    def item_to_dotenv(self, item: dict) -> str:
        chunks: List[str] = []
        notes = (item.get("notes") or "").replace("\r\n", "\n").strip("\n")
        if notes.strip():
            chunks.append(notes.rstrip())
        for field_ in item.get("fields") or []:
            name = (field_.get("name") or "").strip()
            value = field_.get("value")
            if not name or value in (None, ""):
                continue
            chunks.append(f"{name}={value}")
        return "\n".join(chunks)

    def bw_get_item_dotenv(self, name: str) -> Optional[str]:
        item = self.bw_get_item_raw(name)
        if not item:
            return None
        return self.item_to_dotenv(item)

    def cmd_env_status(self) -> int:
        if not self.require_bitwarden() or not self.unlock_bitwarden():
            die("Bitwarden is not ready; see the messages above")
        print(f"context: {self.current_context() or '(none)'}")
        print(f"host: {system.hostname_short()}")
        found = missing = 0
        for name in self.env_item_names():
            result = system.run(["bw", "get", "item", name], capture=True, check=False)
            if result.returncode == 0:
                print(f"found   {name}")
                found += 1
            else:
                print(f"missing {name}")
                missing += 1
        print(
            f"found={found} missing={missing} (missing is ok until you create the item)"
        )
        return 0

    def env_files(self) -> Dict[Path, str]:
        """Each generated env file and the Bitwarden item that belongs to it."""
        names = self.env_item_names()
        if not names:
            return {}
        return {self.home / ".env": names[0], self.home / ".env.host": names[-1]}

    def env_attention(self) -> List[str]:
        """What the last sync left unresolved, read from the files (no Bitwarden)."""
        if not self.current_context():
            return []
        open_items = []
        for path, item in self.env_files().items():
            if not path.is_file():
                continue
            parsed = parse_env_file(path.read_text(encoding="utf-8"))
            if parsed.shell_code and not parsed.generated:
                open_items.append(f"{self.display(path)} contains shell code")
            elif parsed.local_only:
                keys = ", ".join(sorted(set(parsed.local_only)))
                open_items.append(
                    f"{self.display(path)}: {keys} not in Bitwarden {item} "
                    "or ~/.env.local"
                )
        return open_items

    def env_sync_attention(self) -> List[str]:
        """Unpushed local edits and unresolved references (no Bitwarden)."""
        if not self.current_context():
            return []
        open_items = []
        for path in self.env_files():
            if not path.is_file():
                continue
            edits = self.env_unpushed_edits(path)
            if edits:
                open_items.append(
                    f"{self.display(path)}: local edits of {', '.join(edits)} "
                    "not in Bitwarden (push or discard)"
                )
        try:
            unresolved = json.loads(self.env_unresolved_path.read_text())
        except (OSError, ValueError):
            unresolved = []
        for path, key, name, why in unresolved:
            open_items.append(
                f'{self.display(Path(path))}: {key} references Bitwarden "{name}" '
                f"({why})"
            )
        return open_items

    def _env_generated(self, names: List[str]) -> Tuple[Dict[Path, str], int]:
        env_path = self.home / ".env"
        host_path = self.home / ".env.host"
        chunks = {
            path: [
                GENERATED_HEADER,
                "# local overrides in ~/.env.local (never overwritten)",
                *SYNTAX_HINT,
                "# Bitwarden items (later files/fields win):",
                *(f"# - {name}" for name in selected),
                "",
            ]
            for path, selected in (
                (env_path, names[:-1]),
                (host_path, names[-1:]),
            )
        }
        self._env_refs: Dict[str, str] = {}
        self._env_ref_items: Dict[str, Optional[List[dict]]] = {}
        self.env_unresolved: List[Tuple[Path, str, str, str]] = []
        got = 0
        for name in names:
            body = self.bw_get_item_dotenv(name)
            if body:
                if any(
                    match.group(1) == "BW_SESSION"
                    for line in body.splitlines()
                    if (match := ASSIGNMENT.match(line))
                ):
                    die(f"BW_SESSION must remain local; remove it from {name}")
                path = host_path if name == names[-1] else env_path
                body = self._resolve_references(path, body)
                chunks[path].extend(["", f"# --- {name} ---", body.rstrip("\n")])
                got += 1
                log(f"env from {name}")
            else:
                log(f"no Bitwarden item {name} (skip)")
        generated = {
            path: "\n".join(lines).rstrip("\n") + "\n" for path, lines in chunks.items()
        }
        return generated, got

    def _referenced_items(self, name: str) -> Optional[List[dict]]:
        if name not in self._env_ref_items:
            self._env_ref_items[name] = self.bw_items_named(name)
        return self._env_ref_items[name]

    def resolve_reference(self, name: str, target: str) -> Tuple[Optional[str], str]:
        """(value, "") or (None, why it cannot be resolved)."""
        items = self._referenced_items(name)
        if items is None:
            return None, "cannot list Bitwarden items"
        if not items:
            return None, "item not found"
        if len(items) > 1:
            return None, f"{len(items)} items with this name"
        value = reference_value(items[0], target)
        if value is None:
            return None, f"item has no {target}"
        if "\n" in value:
            return None, "multi-line value"
        if "${" in value:
            return None, "value contains ${, which the env file loader expands"
        return value, ""

    def _previous_lines(self, path: Path) -> Dict[str, str]:
        """Lines of the last pull, so an unpushed local edit never becomes the base."""
        source = self.env_state_path(path)
        if not source.is_file():
            source = path
        if not source.is_file():
            return {}
        parsed = parse_env_file(source.read_text(encoding="utf-8"))
        return {
            key: line
            for key, line, _section in parsed.assignments
            if not parse_reference(assignment_parts(line)[2])
        }

    def _resolve_references(self, path: Path, body: str) -> str:
        """Replace reference lines with a comment and a token for the value."""
        previous: Optional[Dict[str, str]] = None
        lines = []
        for line in body.splitlines():
            if line.lstrip().startswith("#") or not ASSIGNMENT.match(line):
                lines.append(line)
                continue
            prefix, key, raw = assignment_parts(line)
            reference = parse_reference(raw)
            if not reference:
                lines.append(line)
                continue
            name, target = reference
            value, why = self.resolve_reference(name, target)
            if value is not None:
                token = f"@@machine-ref:{len(self._env_refs)}@@"
                self._env_refs[token] = value
                lines.append(f'# {key} from Bitwarden "{name}" ({target})')
                lines.append(prefix + token)
                continue
            self.env_unresolved.append((path, key, name, why))
            lines.append(
                f'# unresolved: {key} from Bitwarden "{name}" ({target}): {why}'
            )
            if previous is None:
                previous = self._previous_lines(path)
            if key in previous:
                lines.append(previous[key])
        return "\n".join(lines)

    def render_env(self, text: str) -> str:
        """Write resolved values in the format the shell loader reads for this file."""
        if not REF_TOKEN.search(text):
            return text
        sourced = is_sourced(text)
        refs = getattr(self, "_env_refs", {})

        def value(match: "re.Match[str]") -> str:
            resolved = refs[match.group(0)]
            return shlex.quote(resolved) if sourced else resolved

        return REF_TOKEN.sub(value, text)

    @property
    def env_unresolved_path(self) -> Path:
        """References the last pull could not resolve (keys and items, no values)."""
        return self.state_dir / "env-generated" / "unresolved.json"

    def env_state_path(self, path: Path) -> Path:
        """The content machine last wrote to a generated env file."""
        return self.state_dir / "env-generated" / path.name.lstrip(".")

    def env_unpushed_edits(self, path: Path, new: Optional[str] = None) -> List[str]:
        """Keys from an item that the file changed or removed since the last pull.

        With `new` (the content a pull would write now), a key that already equals
        the new content is not an edit."""
        state = self.env_state_path(path)
        if not state.is_file() or not path.is_file():
            return []
        current = parse_env_file(path.read_text(encoding="utf-8"))
        if current.shell_code:
            return []
        now = {key: line for key, line, _section in current.assignments}
        upcoming = item_lines(parse_env_file(new)) if new is not None else None
        edits = []
        for key, line in item_lines(parse_env_file(state.read_text())).items():
            if same_line(now.get(key), line):
                continue
            if upcoming is not None and same_line(now.get(key), upcoming.get(key)):
                continue
            edits.append(key)
        return sorted(edits)

    def env_local_only(
        self, generated: Dict[Path, str], overlay_text: str
    ) -> List[LocalOnly]:
        sourced = {
            match.group(1)
            for text in (*generated.values(), overlay_text)
            for line in text.splitlines()
            if (match := ASSIGNMENT.match(line))
        }
        reports = []
        for path, item in self.env_files().items():
            if not path.is_file():
                continue
            existing = parse_env_file(path.read_text(encoding="utf-8"))
            report = local_only_content(
                path, item, existing, generated.get(path, ""), sourced
            )
            if report.keys or report.shell_code:
                reports.append(report)
        return reports

    def _choose_for_key(self, report: LocalOnly, key: str) -> str:
        labels = {
            TO_BITWARDEN: f"add to Bitwarden {report.item}",
            KEEP_LOCALLY: "keep locally (~/.env.local)",
            REMOVE: "remove",
            SKIP: "skip (decide later)",
        }
        origin = (
            f" (was in {report.was_in[key]}; deleted there?)"
            if key in report.was_in
            else ""
        )
        print(
            f"\n{self.display(report.path)}: {key} is not set by Bitwarden "
            f"or ~/.env.local{origin}"
        )
        picked = system.choose("Choose", list(labels.values()), labels[SKIP])
        return next(choice for choice, label in labels.items() if label == picked)

    def _choose_for_shell_code(self, report: LocalOnly) -> str:
        labels = {
            KEEP_LOCALLY: "keep locally (append these lines to ~/.env.local)",
            REMOVE: "remove",
            SKIP: f"skip (leave {self.display(report.path)} unchanged)",
        }
        print(
            f"\n{self.display(report.path)} contains shell code that machine cannot sync:"
        )
        for line in report.shell_code:
            print(f"  {line}")
        picked = system.choose("Choose", list(labels.values()), labels[SKIP])
        return next(choice for choice, label in labels.items() if label == picked)

    def _keep_locally(self, path: Path, lines: List[str]) -> None:
        overlay = self.home / ".env.local"
        current = overlay.read_bytes() if overlay.is_file() else b""
        if current and not current.endswith(b"\n"):
            current += b"\n"
        block = "\n".join(
            [f"# kept from {self.display(path)} on {time.strftime('%Y-%m-%d')}", *lines]
        )
        write_private(overlay, current + (block + "\n").encode())
        log(f"kept {len(lines)} line(s) from {self.display(path)} in ~/.env.local")

    def _add_to_bitwarden(self, item_name: str, lines: List[str]) -> bool:
        if system.run(["bw", "sync"], capture=True, check=False).returncode != 0:
            return False
        block = "\n".join(
            [
                f"# added from {system.hostname_short()} on {time.strftime('%Y-%m-%d')}",
                *lines,
            ]
        )
        found = self.bw_items_named(item_name)
        if found is None or len(found) > 1:
            return False
        item = found[0] if found else None
        if item is None:
            created = self.bw_create_item(
                {
                    "type": 2,
                    "name": item_name,
                    "notes": block,
                    "secureNote": {"type": 0},
                }
            )
            return created is not None
        notes = (item.get("notes") or "").rstrip("\n")
        item["notes"] = f"{notes}\n\n{block}" if notes else block
        return self.bw_edit_item(item)

    def fix_env_permissions(self) -> None:
        """Change env files that group or others may access to 0600 (spec env-files)."""
        for path in (
            self.home / ".env",
            self.home / ".env.host",
            self.home / ".env.local",
        ):
            if not path.is_file():
                continue
            mode = stat.S_IMODE(path.stat().st_mode)
            if not mode & 0o077:
                continue
            try:
                path.chmod(0o600)
            except OSError as error:
                warn(
                    f"{self.display(path)} permissions ({mode:o}) are too open "
                    f"and could not be changed ({error}); run: chmod 600 {path}"
                )
                continue
            log(f"fixed permissions of {self.display(path)} ({mode:o} -> 600)")

    def _choose_for_edits(self, path: Path, keys: List[str]) -> str:
        labels = {
            PUSH: "push the edits to Bitwarden now (machine env push)",
            DISCARD: "discard the edits (backup kept)",
            SKIP: f"skip (leave {self.display(path)} unchanged)",
        }
        print(
            f"\n{self.display(path)} has local edits not in Bitwarden: {', '.join(keys)}"
        )
        picked = system.choose("Choose", list(labels.values()), labels[SKIP])
        return next(choice for choice, label in labels.items() if label == picked)

    def _held_edits(
        self, names: List[str], generated: Dict[Path, str], ask: bool, discard
    ) -> Tuple[Dict[Path, List[str]], Dict[Path, str]]:
        """Files whose unpushed local edits stay; pushes the ones the user chose."""
        held: Dict[Path, List[str]] = {}
        pushed = False
        for path, item in self.env_files().items():
            if path in discard:
                continue
            keys = self.env_unpushed_edits(path, self.render_env(generated[path]))
            if not keys:
                continue
            choice = self._choose_for_edits(path, keys) if ask else SKIP
            if choice == PUSH:
                result = self.push_env_file(
                    path, item, self.render_env(generated[path])
                )
                if result in (PUSHED, NOTHING_TO_PUSH):
                    pushed = True
                    continue
            if choice != DISCARD:
                held[path] = keys
        if pushed:
            generated, _got = self._env_generated(names)
        return held, generated

    def cmd_env_pull(self, interactive: bool = False, discard=()) -> int:
        # Before any Bitwarden step, so it also runs locked, without bw and in containers.
        self.fix_env_permissions()
        if not self.current_context():
            log("no context (container): skip ~/.env sync")
            return 0
        if interactive:
            if not self.require_bitwarden():
                return 1
        elif not system.have("bw"):
            log("Bitwarden CLI (bw) not installed; skip ~/.env sync (machine env pull)")
            return 0
        if not self.unlock_bitwarden():
            log("Bitwarden not unlocked; skip ~/.env sync (run machine env pull)")
            return 1 if interactive else 0
        self.offer_saving_bitwarden_session()
        system.run(["bw", "sync"], capture=True)
        names = self.env_item_names()
        generated, got = self._env_generated(names)
        if got == 0:
            log("no env items in Bitwarden; left ~/.env and ~/.env.host unchanged")
            return 0
        overlay = self.home / ".env.local"

        def overlay_text() -> str:
            return overlay.read_text() if overlay.is_file() else ""

        ask = system.is_tty() and not getattr(self, "unattended", False)
        held, generated = self._held_edits(names, generated, ask, discard)
        carry: Dict[Path, List[str]] = {}
        unchanged: List[LocalOnly] = []
        to_bitwarden: Dict[str, List[Tuple[Path, str, List[str]]]] = {}
        reports = [
            report
            for report in self.env_local_only(generated, overlay_text())
            if report.path not in held
        ]
        for report in reports:
            if report.shell_code:
                choice = self._choose_for_shell_code(report) if ask else SKIP
                if choice == SKIP:
                    unchanged.append(report)
                elif choice == KEEP_LOCALLY:
                    self._keep_locally(report.path, report.keep_lines)
                continue
            for key, lines in report.keys.items():
                choice = self._choose_for_key(report, key) if ask else SKIP
                if choice == SKIP:
                    origin = (
                        [f"# was in {report.was_in[key]}"]
                        if key in report.was_in
                        else []
                    )
                    carry.setdefault(report.path, []).extend([*origin, *lines])
                elif choice == KEEP_LOCALLY:
                    self._keep_locally(report.path, lines)
                elif choice == TO_BITWARDEN:
                    to_bitwarden.setdefault(report.item, []).append(
                        (report.path, key, lines)
                    )
        for item_name, entries in to_bitwarden.items():
            lines = [line for _path, _key, key_lines in entries for line in key_lines]
            if self._add_to_bitwarden(item_name, lines):
                log(f"added {len(entries)} key(s) to Bitwarden {item_name}")
                continue
            warn(f"could not write Bitwarden {item_name}; kept the key(s) local-only")
            for path, key, key_lines in entries:
                carry.setdefault(path, []).extend(key_lines)
        if to_bitwarden:
            generated, _got = self._env_generated(names)

        backup_dir = self.state_dir / "env-backup"
        backup_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
        backup_dir.chmod(0o700)
        skipped = {report.path for report in unchanged} | set(held)
        backups: Dict[Path, Path] = {}
        for path, content in generated.items():
            if path in held:
                continue
            if carry.get(path):
                content += "\n" + "\n".join([LOCAL_ONLY_HEADER, *carry[path]]) + "\n"
            content = self.render_env(content)
            existing = path.read_text(encoding="utf-8") if path.is_file() else None
            if path not in skipped:
                write_private(self.env_state_path(path), content.encode())
            if existing is not None and existing != content:
                digest = hashlib.sha256(existing.encode()).hexdigest()[:16]
                backups[path] = backup_dir / f"{path.name.lstrip('.')}.{digest}"
                if not backups[path].exists():
                    write_private(backups[path], existing.encode())
                log(f"backed up existing {path} to {backups[path]}")
            if path not in skipped and existing != content:
                write_private(path, content.encode())
        log(
            f"wrote {', '.join(self.display(p) for p in generated if p not in skipped)} "
            f"from {got} Bitwarden item(s)"
        )
        items = self.env_files()
        for path, lines in carry.items():
            keys = sorted(
                {m.group(1) for line in lines if (m := ASSIGNMENT.match(line))}
            )
            backup = f"; backup: {backups[path]}" if path in backups else ""
            warn(
                f"{self.display(path)}: {', '.join(keys)} not set by Bitwarden "
                f"{items[path]} or ~/.env.local; kept in its local-only section"
                f"{backup}; run: machine attention"
            )
        for report in unchanged:
            backup = (
                f"; backup: {backups[report.path]}" if report.path in backups else ""
            )
            warn(
                f"{self.display(report.path)} contains shell code that machine cannot sync; "
                f"left unchanged{backup}; run: machine attention"
            )
        for path, keys in held.items():
            warn(
                f"{self.display(path)}: local edits of {', '.join(keys)} are not in "
                "Bitwarden; left unchanged; run: machine env push (or machine attention)"
            )
        write_private(
            self.env_unresolved_path,
            json.dumps(
                [
                    [str(path), key, name, why]
                    for path, key, name, why in self.env_unresolved
                ]
            ).encode(),
        )
        for path, key, name, why in self.env_unresolved:
            warn(
                f'{self.display(path)}: {key} references Bitwarden "{name}", which '
                f"cannot be resolved ({why}); kept its previous value, if any; "
                "run: machine attention"
            )
        return 0
