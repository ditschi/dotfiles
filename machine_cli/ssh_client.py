"""SSH client config: host list from Bitwarden, managed host keys, `machine ssh` commands.

Layers (see home/core/.ssh/config): ~/.ssh/config.local, then ~/.ssh/config.d/*
(20-home or 20-work from the Bitwarden note ssh/<class>/config, 90-legacy from the
hand-written config the link replaced), then the shared defaults.
"""

