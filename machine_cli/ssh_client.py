SECURE_NOTE = 2
LOCAL_ONLY_HEADER = (
    "# --- local only: not in Bitwarden (resolve with machine attention) ---"
)
LEGACY_HEADER = (
    "# generated by machine from ~/.ssh/config.pre-dotfiles: hosts of the old config\n"
    "# that the host list lacks; resolve with machine attention"
)
HEADER = re.compile(r"^\s*(host|match)\s+(.*)$", re.IGNORECASE)
OPTION = re.compile(r"^\s*([A-Za-z]+)\s*[= ]\s*(.*)$")
KEY_DIRS = ("machine/ssh_keys", "machine/ssh_host_keys")

ADD = "bitwarden"
LOCAL = "local"
REMOVE = "remove"
SKIP = "skip"


@dataclass
class Block:
    """One `Host`/`Match` section with its lines as written."""

    header: str
    lines: List[str] = field(default_factory=list)

    @property
    def names(self) -> List[str]:
        match = HEADER.match(self.header)
        if not match or match.group(1).lower() != "host":
            return []
        return [name.lower() for name in match.group(2).split()]

    @property
    def norm(self) -> Tuple[str, ...]:
        return tuple(
            " ".join(line.split())
            for line in self.lines
            if line.strip() and not line.lstrip().startswith("#")
        )

    def option(self, name: str) -> str:
        for line in self.lines[1:]:
            match = OPTION.match(line)
            if match and match.group(1).lower() == name.lower():
                return match.group(2).strip()
        return ""

    def text(self) -> str:
        return "\n".join(self.lines).rstrip("\n")


def parse_blocks(text: str) -> Tuple[List[str], List[Block]]:
    """(lines before the first section, sections); comment lines stay with the
    section they follow, blank lines before a header are dropped from both."""
    preamble: List[str] = []
    blocks: List[Block] = []
    for line in text.splitlines():
        if HEADER.match(line):
            blocks.append(Block(line, [line]))
        elif blocks:
            blocks[-1].lines.append(line)
        else:
            preamble.append(line)
    for block in blocks:
        while block.lines and not block.lines[-1].strip():
            block.lines.pop()
    return preamble, blocks


def defined_names(text: str) -> set:
    return {name for block in parse_blocks(text)[1] for name in block.names}


def without_blocks(text: str, alias: str) -> Tuple[str, List[Block]]:
    """`text` without the sections that define `alias`, and the removed sections."""
    preamble, blocks = parse_blocks(text)
    kept = [b for b in blocks if alias.lower() not in b.names]
    removed = [b for b in blocks if alias.lower() in b.names]
    parts = ["\n".join(preamble).strip("\n")] + [b.text() for b in kept]
    return "\n\n".join(part for part in parts if part).rstrip("\n") + "\n", removed


def render_block(
    alias: str,
    *,
    address: str = "",
    user: str = "",
    port: int = 22,
    host_key_alias: str = "",
    routes: Optional[Dict[str, str]] = None,
    names: Sequence[str] = (),
) -> str:
    lines = [f"Host {' '.join([alias, *names])}"]
    if address and not routes:
        lines.append(f"  HostName {address}")
    if user:
        lines.append(f"  User {user}")
    if port != 22 and not routes:
        lines.append(f"  Port {port}")
    if host_key_alias:
        lines.append(f"  HostKeyAlias {host_key_alias}")
    if routes:
        parts = " ".join(f"{k}={v}" for k, v in routes.items() if v)
        lines.append(f"  ProxyCommand ~/.local/bin/ssh-route %k {parts}")
    return "\n".join(lines)


def blobs(text: str) -> List[str]:
    return [key_blob(line) for line in text.splitlines() if line.strip()]


class SshClientMixin:
    # --- paths ------------------------------------------------------------------

    @property
    def ssh_dir(self) -> Path:
        return self.home / ".ssh"

    def ssh_list_item(self, context: Optional[str] = None) -> str:
        klass = self.ssh_class(context)
        return f"ssh/{klass}/config" if klass else ""

    def ssh_list_path(self) -> Optional[Path]:
        klass = self.ssh_class()
        return self.ssh_dir / "config.d" / f"20-{klass}" if klass else None

    def ssh_list_snapshot(self) -> Path:
        return self.state_dir / f"ssh-host-list.{self.ssh_class() or 'none'}"

    @property
    def ssh_legacy_path(self) -> Path:
        return self.ssh_dir / "config.d" / "90-legacy"

    @property
    def ssh_known_hosts_path(self) -> Path:
        return self.ssh_dir / "known_hosts.d" / "home"

    @property
    def ssh_route_cache(self) -> Path:
        base = os.environ.get("XDG_CACHE_HOME") or str(self.home / ".cache")
        return Path(base) / "ssh-route" / "networks"

    def host_keys_dir(self) -> Path:
        return self.repo / "machine" / "ssh_host_keys"

    def ssh_private_host(self) -> bool:
        return self.ssh_class() == "home" and not system.in_docker()

    # --- apply (no Bitwarden; also in the background update) --------------------

    def apply_ssh_client(self) -> None:
        for path in (self.ssh_dir, self.ssh_dir / "cm", self.ssh_dir / "config.d"):
            path.mkdir(mode=0o700, parents=True, exist_ok=True)
            path.chmod(0o700)
        base = self.repo / "home" / "core" / ".ssh" / "config"
        if base.is_file() and base.stat().st_mode & 0o022:
            base.chmod(base.stat().st_mode & ~0o022)
            log(f"made {base.relative_to(self.repo)} not writable for group and others")
        self.write_known_hosts()
        self.write_legacy_ssh_config()

    def write_known_hosts(self) -> None:
        path = self.ssh_known_hosts_path
        if not self.ssh_private_host():
            if path.is_file():
                path.unlink()
                log(f"removed {self.display(path)} (not a private host)")
            return
        lines = []
        for source in sorted(self.host_keys_dir().glob("*.pub")):
            fields = source.read_text(encoding="utf-8").split()
            if len(fields) >= 2:
                lines.append(f"{source.stem} {fields[0]} {fields[1]}")
        text = (
            "# generated by machine from machine/ssh_host_keys/ — do not edit\n"
            + "".join(f"{line}\n" for line in lines)
        )
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            return
        path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        path.chmod(0o644)
        log(f"wrote {self.display(path)} ({len(lines)} host key(s))")

    def legacy_ssh_sources(self) -> List[Path]:
        return sorted(
            p
            for p in self.ssh_dir.glob("config.pre-dotfiles*")
            if p.is_file() and not p.is_symlink()
        )

    def write_legacy_ssh_config(self) -> None:
        """Hosts of the replaced config that neither the host list nor
        ~/.ssh/config.local defines, so nothing breaks before the list exists."""
        sources = self.legacy_ssh_sources()
        path = self.ssh_legacy_path
        if not sources:
            if path.is_file():
                path.unlink()
            return
        managed = set()
        for other in (self.ssh_list_path(), self.ssh_dir / "config.local"):
            if other and other.is_file():
                managed |= defined_names(other.read_text(encoding="utf-8"))
        chunks = [LEGACY_HEADER]
        hosts = 0
        for source in sources:
            preamble, blocks = parse_blocks(source.read_text(encoding="utf-8"))
            kept = [b for b in blocks if not (set(b.names) & managed)]
            options = [
                line
                for line in preamble
                if line.strip() and not line.lstrip().startswith("#")
            ]
            if options:
                chunks.append("\n".join(options))
            chunks.extend(block.text() for block in kept)
            hosts += len(kept)
        if hosts == 0 and len(chunks) == 1:
            if path.is_file():
                path.unlink()
            return
        text = "\n\n".join(chunks) + "\n"
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            return
        write_private(path, text.encode())
        log(
            f"wrote {self.display(path)}: {hosts} host(s) of the replaced ~/.ssh/config"
        )

    # --- host list from Bitwarden ------------------------------------------------

    def check_ssh_config(self, text: str) -> str:
        """Empty when ssh accepts `text`, else ssh's message."""
        with tempfile.NamedTemporaryFile(
            "w", prefix="machine-ssh-", suffix=".conf", delete=False
        ) as handle:
            handle.write(text)
            name = handle.name
        try:
            result = system.run(
                ["ssh", "-G", "-F", name, "machine-config-check"],
                capture=True,
                check=False,
            )
        finally:
            os.unlink(name)
        if result.returncode == 0:
            return ""
        return " ".join((result.stderr or "").replace(name, "<note>").split()) or (
            "ssh rejected the config"
        )

    def ssh_list_note(self) -> Tuple[bool, Optional[dict]]:
        """(listed, secure note of the host list); after `bw sync`."""
        items = self.bw_items_named(self.ssh_list_item())
        if items is None:
            return False, None
        return True, next((i for i in items if i.get("type") == SECURE_NOTE), None)

    def ssh_list_ready(self, interactive: bool) -> bool:
        if not self.ssh_list_item():
            return False
        if interactive:
            return self.require_bitwarden() and self.unlock_bitwarden()
        if not system.have("bw"):
            log("SSH host list not updated: Bitwarden CLI (bw) is not installed")
            return False
        if not self.bitwarden_session_ready():
            warn(
                "SSH host list not updated: Bitwarden is not unlocked. "
                "Log in with `machine env pull` in a terminal"
            )
            return False
        return True

    def local_ssh_blocks(self, notes: str) -> List[Block]:
        """Sections of the generated file that are not in the note (see spec)."""
        path = self.ssh_list_path()
        if not path or not path.is_file():
            return []
        text = path.read_text(encoding="utf-8")
        generated, _sep, local_part = text.partition(LOCAL_ONLY_HEADER)
        snapshot = self.ssh_list_snapshot()
        last = (
            {b.norm for b in parse_blocks(snapshot.read_text(encoding="utf-8"))[1]}
            if snapshot.is_file()
            else set()
        )
        current = {b.norm for b in parse_blocks(notes)[1]}
        candidates = [b for b in parse_blocks(generated)[1] if b.norm not in last]
        candidates += parse_blocks(local_part)[1]
        result, seen = [], set()
        for block in candidates:
            if block.norm in current or block.norm in seen:
                continue
            seen.add(block.norm)
            result.append(block)
        return result

    def _choose_for_block(self, block: Block) -> str:
        item = self.ssh_list_item()
        labels = {
            ADD: f"add to Bitwarden {item}",
            LOCAL: "move to ~/.ssh/config.local",
            REMOVE: "remove",
            SKIP: "skip (decide later)",
        }
        print(
            f"\n{self.display(self.ssh_list_path())}: local host block not in {item}:"
        )
        for line in block.lines:
            print(f"  {line}")
        picked = system.choose("Choose", list(labels.values()), labels[SKIP])
        return next(choice for choice, label in labels.items() if label == picked)

    def append_ssh_config_local(self, lines: List[str]) -> None:
        path = self.ssh_dir / "config.local"
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current and not current.endswith("\n"):
            current += "\n"
        block = "\n".join(
            [f"# moved here by machine on {time.strftime('%Y-%m-%d')}", *lines]
        )
        sep = "\n" if current else ""
        write_private(path, (current + sep + block + "\n").encode())
        log(f"wrote {len(lines)} line(s) to ~/.ssh/config.local")

    def write_ssh_host_list(self, notes: str, carry: List[Block]) -> None:
        path = self.ssh_list_path()
        assert path is not None
        text = (
            f"# generated by machine from Bitwarden {self.ssh_list_item()} — "
            "change it with machine ssh add/edit/remove\n\n" + notes.strip("\n") + "\n"
        )
        if carry:
            text += (
                "\n"
                + LOCAL_ONLY_HEADER
                + "\n"
                + "\n\n".join(b.text() for b in carry)
                + "\n"
            )
        path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            write_private(path, text.encode())
            log(f"wrote {self.display(path)} from {self.ssh_list_item()}")
        self.ensure_dirs()
        write_private(self.ssh_list_snapshot(), (notes.strip("\n") + "\n").encode())

    def pull_ssh_host_list(self, interactive: bool = False) -> int:
        if not self.current_context() or system.in_docker():
            return 0
        if not self.ssh_list_ready(interactive):
            return 1 if interactive else 0
        system.run(["bw", "sync"], capture=True, check=False)
        listed, note = self.ssh_list_note()
        item = self.ssh_list_item()
        if not listed:
            warn(f"cannot list Bitwarden items; {item} not read")
            return 1 if interactive else 0
        if not note:
            log(f"no Bitwarden note {item}; create it with: machine ssh add")
            return 0
        notes = (note.get("notes") or "").replace("\r\n", "\n")
        problem = self.check_ssh_config(notes)
        if problem:
            warn(f"{item} not written, ssh rejects it: {problem}")
            return 1 if interactive else 0
        ask = system.is_tty() and not getattr(self, "unattended", False)
        carry: List[Block] = []
        to_bitwarden: List[Block] = []
        for block in self.local_ssh_blocks(notes):
            choice = self._choose_for_block(block) if ask else SKIP
            if choice == SKIP:
                carry.append(block)
            elif choice == LOCAL:
                self.append_ssh_config_local(block.lines)
            elif choice == ADD:
                to_bitwarden.append(block)
        if to_bitwarden:
            lines = [line for b in to_bitwarden for line in ("", *b.lines)][1:]
            if self._add_to_bitwarden(item, lines):
                log(f"added {len(to_bitwarden)} host block(s) to Bitwarden {item}")
                listed, note = self.ssh_list_note()
                notes = (note or {}).get("notes") or notes
            else:
                warn(f"could not write Bitwarden {item}; kept the block(s) local-only")
                carry.extend(to_bitwarden)
        self.write_ssh_host_list(notes, carry)
        if carry:
            warn(
                f"{self.display(self.ssh_list_path())}: "
                f"{', '.join(' '.join(b.names) or b.header for b in carry)} not in "
                f"Bitwarden {item}; kept in its local-only section; run: machine attention"
            )
        self.write_legacy_ssh_config()
        return 0

    # --- writing the note --------------------------------------------------------

    def save_ssh_list_note(self, notes: str) -> bool:
        """Replace the note text (after a sync); create the note when missing."""
        item = self.ssh_list_item()
        if system.run(["bw", "sync"], capture=True, check=False).returncode != 0:
            return False
        listed, note = self.ssh_list_note()
        if not listed:
            return False
        if note is None:
            return (
                self.bw_create_item(
                    {
                        "type": SECURE_NOTE,
                        "name": item,
                        "notes": notes,
                        "secureNote": {"type": 0},
                    }
                )
                is not None
            )
        note["notes"] = notes
        return self.bw_edit_item(note)

    def current_ssh_list_notes(self) -> Optional[str]:
        system.run(["bw", "sync"], capture=True, check=False)
        listed, note = self.ssh_list_note()
        if not listed:
            return None
        return ((note or {}).get("notes") or "").replace("\r\n", "\n")

    # --- repository key files ------------------------------------------------------

    def write_repo_key_file(self, path: Path, public: str) -> bool:
        line = public.strip()
        if path.is_file() and blobs(path.read_text(encoding="utf-8")) == [
            key_blob(line)
        ]:
            return False
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(line + "\n", encoding="utf-8")
        log(f"wrote {path.relative_to(self.repo)}; commit and push it")
        return True

    def sync_repo_key_files(self) -> None:
        """Home hosts: the selected user key and the sshd host key in the repo."""
        if not self.ssh_private_host():
            return
        host = system.hostname_short()
        private = self.saved_ssh_key()
        public = self.ensure_public_key(private) if private else None
        if public and public.is_file():
            self.write_repo_key_file(
                self.repo / "machine" / "ssh_keys" / f"{host}.pub",
                public.read_text(encoding="utf-8").splitlines()[0],
            )
        host_key = Path(
            os.environ.get(
                "MACHINE_SSH_HOST_KEY_FILE", "/etc/ssh/ssh_host_ed25519_key.pub"
            )
        )
        if host_key.is_file():
            fields = host_key.read_text(encoding="utf-8").split()
            if len(fields) >= 2:
                self.write_repo_key_file(
                    self.host_keys_dir() / f"{host}.pub",
                    f"{fields[0]} {fields[1]} {host}",
                )

    def unpushed_key_files(self) -> List[str]:
        git = ["git", "-C", str(self.repo)]
        status = system.run(
            [*git, "status", "--porcelain", "--untracked-files=all", "--", *KEY_DIRS],
            capture=True,
            check=False,
        )
        files = [
            line[3:] for line in (status.stdout or "").splitlines() if line.strip()
        ]
        ahead = system.run(
            [*git, "log", "@{u}..HEAD", "--name-only", "--format=", "--", *KEY_DIRS],
            capture=True,
            check=False,
        )
        if ahead.returncode == 0:
            files += [line for line in ahead.stdout.splitlines() if line.strip()]
        return sorted(set(files))

    def push_key_files(self) -> int:
        git = ["git", "-C", str(self.repo)]
        system.run([*git, "add", "--", *KEY_DIRS], check=False)
        staged = system.run(
            [*git, "diff", "--cached", "--quiet", "--", *KEY_DIRS], check=False
        )
        if staged.returncode != 0:
            system.run(
                [*git, "commit", "-m", f"ssh: key files of {system.hostname_short()}",
                 "--", *KEY_DIRS]
            )  # fmt: skip
        return system.run([*git, "push"], check=False).returncode

    # --- learned home gateways (ssh-route cache) -----------------------------------

    def ssh_route_networks(self) -> dict:
        try:
            data = json.loads(self.ssh_route_cache.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return {}
        return data if isinstance(data, dict) else {}

    def old_home_gateways(self) -> List[str]:
        """Older home gateways next to the newest one, unless kept by the user."""
        homes = sorted(
            (
                (float(v.get("seen", 0)), mac)
                for mac, v in self.ssh_route_networks().items()
                if isinstance(v, dict) and v.get("state") == "home"
            ),
            reverse=True,
        )
        networks = self.ssh_route_networks()
        return [mac for _seen, mac in homes[1:] if not networks[mac].get("kept")]

    def resolve_home_gateways(self) -> int:
        networks = self.ssh_route_networks()
        old = self.old_home_gateways()
        if not old:
            return 0
        remove, keep = "remove the older entries", "keep both"
        choice = system.choose("ssh-route home gateways", [remove, keep], remove)
        for mac in old:
            if choice == remove:
                networks.pop(mac, None)
            else:
                networks[mac]["kept"] = True
        self.ssh_route_cache.write_text(
            json.dumps(networks, indent=1, sort_keys=True) + "\n"
        )
        log("removed the older home gateway(s)" if choice == remove else "kept both")
        return 0

    # --- attention -------------------------------------------------------------------

    def ssh_attention(self) -> List[Tuple[str, str, Optional[str], object]]:
        """(kind, text, question, resolve) of the open SSH items (no Bitwarden)."""
        items: List[Tuple[str, str, Optional[str], object]] = []
        path = self.ssh_list_path()
        if path and path.is_file():
            text = path.read_text(encoding="utf-8")
            if LOCAL_ONLY_HEADER in text:
                names = [
                    " ".join(b.names) or b.header
                    for b in parse_blocks(text.partition(LOCAL_ONLY_HEADER)[2])[1]
                ]
                items.append(
                    (
                        "ssh",
                        f"local SSH host blocks not in {self.ssh_list_item()}: "
                        + ", ".join(names),
                        "Resolve them now (machine ssh pull)?",
                        lambda: self.pull_ssh_host_list(interactive=True),
                    )
                )
        if self.ssh_legacy_path.is_file():
            names = sorted(
                defined_names(self.ssh_legacy_path.read_text(encoding="utf-8"))
            )
            items.append(
                (
                    "ssh",
                    "hosts still taken from the replaced ~/.ssh/config: "
                    + (", ".join(names) or "global options only"),
                    None,
                    self.resolve_legacy_ssh_config,
                )
            )
        unpushed = self.unpushed_key_files()
        if unpushed:
            items.append(
                (
                    "ssh",
                    "SSH key files not pushed yet: " + ", ".join(unpushed),
                    "Commit and push them now?",
                    self.push_key_files,
                )
            )
        if self.old_home_gateways():
            items.append(
                (
                    "ssh",
                    "ssh-route learned a new home gateway; an older one is still stored",
                    None,
                    self.resolve_home_gateways,
                )
            )
        return items

    def resolve_legacy_ssh_config(self) -> int:
        """Each host of the old config: to Bitwarden, to config.local, or drop."""
        if not self.ssh_legacy_path.is_file():
            return 0
        _pre, blocks = parse_blocks(self.ssh_legacy_path.read_text(encoding="utf-8"))
        item = self.ssh_list_item()
        labels = {
            ADD: f"add to Bitwarden {item}" if item else "",
            LOCAL: "move to ~/.ssh/config.local",
            REMOVE: "drop it",
            SKIP: "skip (decide later)",
        }
        labels = {k: v for k, v in labels.items() if v}
        done: set = set()
        to_bitwarden: List[Block] = []
        for block in blocks:
            print(f"\nold ~/.ssh/config: {block.header.strip()}")
            for line in block.lines[1:]:
                print(f"  {line}")
            picked = system.choose("Choose", list(labels.values()), labels[SKIP])
            choice = next(c for c, label in labels.items() if label == picked)
            if choice == LOCAL:
                self.append_ssh_config_local(block.lines)
            elif choice == ADD:
                to_bitwarden.append(block)
            if choice != SKIP:
                done.add(block.norm)
        if to_bitwarden:
            if not self.ssh_list_ready(True):
                return 1
            lines = [line for b in to_bitwarden for line in ("", *b.lines)][1:]
            if not self._add_to_bitwarden(item, lines):
                warn(
                    f"could not write Bitwarden {item}; the hosts stay in the old config"
                )
                done -= {b.norm for b in to_bitwarden}
        for source in self.legacy_ssh_sources():
            preamble, source_blocks = parse_blocks(source.read_text(encoding="utf-8"))
            rest = [b for b in source_blocks if b.norm not in done]
            if not rest:
                backup = self.state_dir / "ssh-backup" / source.name
                backup.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
                source.replace(backup)
                log(f"old ~/.ssh/config resolved; kept a copy in {backup}")
                continue
            parts = ["\n".join(preamble).strip("\n")] + [b.text() for b in rest]
            source.write_text(
                "\n\n".join(p for p in parts if p) + "\n", encoding="utf-8"
            )
        if to_bitwarden:
            self.pull_ssh_host_list()
        self.write_legacy_ssh_config()
        return 0

