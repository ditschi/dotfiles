    def ssh_resolve(self, alias: str) -> Dict[str, str]:
        """`ssh -G` values (lower-case keys) for `alias`."""
        result = system.run(["ssh", "-G", alias], capture=True, check=False)
        values: Dict[str, str] = {}
        for line in (result.stdout or "").splitlines():
            key, _sep, value = line.partition(" ")
            values.setdefault(key, value.strip())
        return values

    def scan_host_key(self, address: str, port: int) -> str:
        result = system.run(
            ["ssh-keyscan", "-T", "5", "-t", "ed25519", "-p", str(port), address],
            capture=True,
            check=False,
        )
        for line in (result.stdout or "").splitlines():
            fields = line.split()
            if not line.startswith("#") and len(fields) >= 3:
                return f"{fields[1]} {fields[2]}"
        return ""

    def add_known_host(self, name: str, address: str = "", port: int = 22) -> int:
        """Fetch, show and (after confirmation) store the host key of `name`."""
        if not self.ssh_private_host():
            log("managed host keys exist only on private hosts")
            return 1
        if not system.is_tty():
            warn("machine ssh known-hosts add needs a terminal to confirm the key")
            return 1
        if not address:
            values = self.ssh_resolve(name)
            address = values.get("hostname", name)
            port = int(values.get("port", "22") or 22)
            name = values.get("hostkeyalias") or name
        if address == "localhost":
            warn(f"{name} is reached through a tunnel; add its key on the home network")
            return 1
        key = self.scan_host_key(address, port)
        if not key:
            warn(f"no ed25519 host key from {address}:{port}")
            return 1
        path = self.host_keys_dir() / f"{name}.pub"
        print(f"{name} ({address}:{port}): {key_fingerprint(key)}")
        if path.is_file():
            stored = path.read_text(encoding="utf-8")
            if blobs(stored) == [key_blob(key)]:
                print(f"{path.relative_to(self.repo)} already holds this key")
                return 0
            print(f"stored key: {key_fingerprint(stored.splitlines()[0])}")
            if not system.prompt_yes_no(f"Replace the stored key of {name}?", False):
                return 0
        elif not system.prompt_yes_no(f"Trust this host key for {name}?", False):
            return 0
        self.write_repo_key_file(path, f"{key} {name}")
        self.write_known_hosts()
        return 0

    def ssh_alias_taken(self, alias: str, notes: str) -> Tuple[str, List[Block]]:
        """('list'|'local'|'', blocks) where `alias` is already defined."""
        _text, removed = without_blocks(notes, alias)
        if removed:
            return "list", removed
        local = self.ssh_dir / "config.local"
        if local.is_file():
            _text, removed = without_blocks(local.read_text(encoding="utf-8"), alias)
            if removed:
                return "local", removed
        return "", []

    def primary_address(self) -> str:
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as probe:
                probe.connect(("192.0.2.1", 9))
                return probe.getsockname()[0]
        except OSError:
            return ""

    def cmd_ssh_add(
        self,
        alias: str = "",
        *,
        address: str = "",
        user: str = "",
        offer: bool = False,
    ) -> int:
        """Ask for a host, show its block and write it to the list or config.local."""
        item = self.ssh_list_item()
        if not system.is_tty():
            warn("machine ssh add needs a terminal")
            return 1
        notes = ""
        if item and self.ssh_list_ready(True):
            notes = self.current_ssh_list_notes() or ""
        alias = alias or click.prompt("Alias").strip()
        where, existing = self.ssh_alias_taken(alias, notes)
        if existing:
            print(
                f"{alias} is already defined ({'host list' if where == 'list' else '~/.ssh/config.local'}):"
            )
            for block in existing:
                print(block.text())
            if not system.prompt_yes_no(f"Replace {alias}?", False):
                return 0
        private = self.ssh_private_host()
        routes: Dict[str, str] = {}
        address = click.prompt("Address", default=address or alias).strip()
        user = click.prompt("User", default=user or getpass.getuser()).strip()
        port = click.prompt("Port", default=22, type=int)
        if (
            private
            and not offer
            and system.prompt_yes_no(
                "Home host that is also reached from outside (lan/Tailscale/jump host)?",
                False,
            )
        ):
            jump = click.prompt("Jump host", default="oracle").strip()
            tunnel = click.prompt("Tunnel port on the jump host", type=int)
            tailscale = click.prompt(
                "Tailscale name (empty: none)", default="", show_default=False
            ).strip()
            routes = {
                "lan": f"{address}:{port}",
                "ts": f"{tailscale}:{port}" if tailscale else "",
                "jump": f"{jump}:{tunnel}",
            }
        targets = []
        if item:
            targets.append(f"host list {item} (all hosts of this context)")
        targets.append("this host only (~/.ssh/config.local)")
        target = system.choose("Where", targets, targets[0])
        to_list = bool(item) and target == targets[0]
        block = render_block(
            alias,
            address=address,
            user=user,
            port=port,
            host_key_alias=alias if private else "",
            routes=routes or None,
        )
        print("\n" + block + "\n")
        if not system.prompt_yes_no("Write this host block?", True):
            return 0
        if to_list:
            current = self.current_ssh_list_notes()
            if current is None:
                warn(f"cannot read Bitwarden {item}; nothing written")
                return 1
            rest, _removed = without_blocks(current, alias)
            text = (rest.strip("\n") + "\n\n" + block).strip("\n") + "\n"
            stamp = (
                f"# added from {system.hostname_short()} on {time.strftime('%Y-%m-%d')}"
            )
            text = text.replace(block, f"{stamp}\n{block}", 1)
            if not self.save_ssh_list_note(text):
                warn(f"could not write Bitwarden {item}; nothing changed")
                return 1
            log(f"wrote {alias} to Bitwarden {item}")
            self.pull_ssh_host_list()
        else:
            local = self.ssh_dir / "config.local"
            if where == "local" and local.is_file():
                rest, _ = without_blocks(local.read_text(encoding="utf-8"), alias)
                write_private(local, rest.encode())
            self.append_ssh_config_local(block.splitlines())
        if private and not offer:
            self.add_known_host(alias, address, port)
        if not offer:
            self.ssh_login_test(alias)
        return 0

    def ssh_login_test(self, alias: str) -> bool:
        result = system.run(
            ["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=8", alias, "true"],
            capture=True,
            check=False,
        )
        if result.returncode == 0:
            log(f"login test for {alias}: ok")
            return True
        reason = (result.stderr or "").strip().splitlines()
        warn(f"login test for {alias} failed: {reason[-1] if reason else 'no answer'}")
        print(
            f"  install your key on the target: ssh-copy-id {alias}\n"
            "  or, for a home host managed by machine, add this host to its "
            "ssh_allow_from (machine/hosts/<host>.yml) and run machine apply there"
        )
        return False

    def cmd_ssh_edit(self) -> int:
        item = self.ssh_list_item()
        if not item:
            warn("no SSH host list for this host (no context)")
            return 1
        if not self.ssh_list_ready(True):
            return 1
        current = self.current_ssh_list_notes()
        if current is None:
            warn(f"cannot read Bitwarden {item}")
            return 1
        editor = os.environ.get("VISUAL") or os.environ.get("EDITOR") or "vi"
        text = current
        while True:
            with tempfile.NamedTemporaryFile(
                "w", prefix="ssh-config-", suffix=".conf", delete=False
            ) as handle:
                handle.write(text)
                name = handle.name
            os.chmod(name, 0o600)
            system.run([*editor.split(), name], check=False)
            text = Path(name).read_text(encoding="utf-8")
            os.unlink(name)
            if text == current:
                log("no changes")
                return 0
            problem = self.check_ssh_config(text)
            if not problem:
                break
            warn(f"ssh rejects the text: {problem}")
            again, discard = "edit again", "discard the changes"
            if system.choose("Choose", [again, discard], again) == discard:
                return 0
        if not self.save_ssh_list_note(text):
            warn(f"could not write Bitwarden {item}; nothing changed")
            return 1
        log(f"saved Bitwarden {item}")
        return self.pull_ssh_host_list()

    def cmd_ssh_remove(self, alias: str) -> int:
        item = self.ssh_list_item()
        notes = ""
        if item and self.ssh_list_ready(True):
            notes = self.current_ssh_list_notes() or ""
        where, blocks = self.ssh_alias_taken(alias, notes)
        if not blocks:
            warn(f"{alias} is not in {item or 'the host list'} or ~/.ssh/config.local")
            return 1
        for block in blocks:
            print(block.text())
        if not system.prompt_yes_no(f"Remove {alias}?", False):
            return 0
        if where == "list":
            rest, _ = without_blocks(notes, alias)
            if not self.save_ssh_list_note(rest):
                warn(f"could not write Bitwarden {item}; nothing changed")
                return 1
            log(f"removed {alias} from Bitwarden {item}")
            self.pull_ssh_host_list()
        else:
            local = self.ssh_dir / "config.local"
            rest, _ = without_blocks(local.read_text(encoding="utf-8"), alias)
            write_private(local, rest.encode())
            log(f"removed {alias} from ~/.ssh/config.local")
        if self.ssh_private_host():
            name = next(
                (b.option("HostKeyAlias") for b in blocks if b.option("HostKeyAlias")),
                alias,
            )
            path = self.host_keys_dir() / f"{name}.pub"
            if path.is_file():
                path.unlink()
                log(f"removed {path.relative_to(self.repo)}; commit and push it")
            self.write_known_hosts()
        return 0

    def offer_self_in_host_list(self, yes: bool) -> None:
        """Setup: offer to add this host to the host list of its context."""
        item = self.ssh_list_item()
        if yes or not item or not system.is_tty() or system.in_docker():
            return
        if not self.bitwarden_session_ready():
            return
        notes = self.current_ssh_list_notes()
        host = system.hostname_short()
        if notes is None or host.lower() in defined_names(notes):
            return
        if not system.prompt_yes_no(
            f"Add this host to the SSH host list {item}?", False
        ):
            return
        self.cmd_ssh_add(
            host, address=self.primary_address(), user=getpass.getuser(), offer=True
        )
