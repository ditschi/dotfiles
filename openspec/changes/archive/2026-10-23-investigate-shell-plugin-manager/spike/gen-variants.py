#!/usr/bin/env python3
"""Generate the per-plugin ladder and the head-to-head alternatives as sheldon configs.

  configs/ladder-{sync,defer}-NN-<step>/   one plugin added per step, in final order
  configs/alt-<name>/                      the full deferred sheldon config with one swap

Generated directories are git-ignored; re-run this script to recreate them.
"""
import shutil
import stat
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONFIGS = HERE / "configs"
REPO = HERE.parents[3]
DEFER_OPTS = "-dmpr"

HEADER = """shell = "zsh"

[templates]
defer = "{{% for file in files %}}zsh-defer {opts} source \\"{{{{ file }}}}\\"\\n{{% endfor %}}"
lscolors = "zsh-defer {opts} spike_lscolors \\"{{{{ dir }}}}/LS_COLORS\\""
lscolors_sync = "spike_lscolors \\"{{{{ dir }}}}/LS_COLORS\\""

[plugins.zsh-defer]
github = "romkatv/zsh-defer"
"""


def gh(name, repo, defer, extra=""):
    apply = '\napply = ["defer"]' if defer else ""
    return f'[plugins.{name}]\ngithub = "{repo}"{apply}{extra}\n'


def inline(name, code, defer):
    if defer:
        code = f"zsh-defer {DEFER_OPTS} -c '{code}'"
    return f'[plugins.{name}]\ninline = "{code}"\n'


# (step name, toml block builder(defer) -> str), final order
STEPS = [
    (
        "completions",
        lambda d: '[plugins.zsh-completions]\ngithub = "zsh-users/zsh-completions"\ndir = "src"\napply = ["fpath"]\n',
    ),
    (
        "ls-colors",
        lambda d: '[plugins.ls-colors]\ngithub = "trapd00r/LS_COLORS"\nuse = ["LS_COLORS"]\n'
        f'apply = ["{"lscolors" if d else "lscolors_sync"}"]\n',
    ),
    ("compinit", lambda d: inline("compinit", "spike_compinit", d)),
    ("fzf", lambda d: inline("fzf", "spike_cache_eval fzf fzf --zsh", d)),
    (
        "zoxide",
        lambda d: inline("zoxide", "spike_cache_eval zoxide zoxide init zsh", d),
    ),
    ("fzf-tab", lambda d: gh("fzf-tab", "Aloxaf/fzf-tab", d)),
    ("sudo", lambda d: gh("zsh-sudo", "hcgraf/zsh-sudo", d)),
    ("undollar", lambda d: gh("undollar", "zpm-zsh/undollar", d)),
    (
        "hss",
        lambda d: gh("hss", "zsh-users/zsh-history-substring-search", d)
        + "\n"
        + inline("hss-keys", "spike_after_hss", d),
    ),
    (
        "autosuggest",
        lambda d: gh("autosuggest", "zsh-users/zsh-autosuggestions", d)
        + "\n"
        + inline(
            "autosuggest-start", "_zsh_autosuggest_start; spike_after_autosuggest", d
        ),
    ),
    ("fsh", lambda d: gh("fsh", "zdharma-continuum/fast-syntax-highlighting", d)),
]

ZSHRC = """# Generated by gen-variants.py ({name}).
{pre}source ~/.zsh/common.zsh
{prompt}
() {{
  local toml=${{XDG_CONFIG_HOME:-$HOME/.config}}/sheldon/plugins.toml f=$SPIKE_CACHE/sheldon.zsh
  if [[ ! -s $f || $toml -nt $f || ${{commands[sheldon]}} -nt $f ]]; then
    mkdir -p -- $SPIKE_CACHE
    sheldon source >| $f && zcompile -R -- $f.zwc $f
  fi
  source $f
}}
{post}"""

STARSHIP = "spike_cache_eval starship starship init zsh --print-full-init"
P10K_PRE = """if [[ -r "${XDG_CACHE_HOME:-$HOME/.cache}/p10k-instant-prompt-${(%):-%n}.zsh" ]]; then
  source "${XDG_CACHE_HOME:-$HOME/.cache}/p10k-instant-prompt-${(%):-%n}.zsh"
fi
"""
MISE_ENV = "export MISE_DATA_DIR=/opt/mise MISE_CONFIG_DIR=/opt/mise/config\n"


def write(
    name,
    blocks,
    defer,
    pre="",
    prompt=STARSHIP,
    post="",
    opts=DEFER_OPTS,
    extra_files=None,
):
    d = CONFIGS / name
    shutil.rmtree(d, ignore_errors=True)
    (d / "skel/.config/sheldon").mkdir(parents=True)
    loaded = inline("loaded", "spike_loaded", defer)
    toml = HEADER.format(opts=opts) + "\n" + "\n".join(blocks + [loaded])
    if opts != DEFER_OPTS:
        toml = toml.replace(
            f"zsh-defer {DEFER_OPTS} ", f"zsh-defer {opts} ".replace("  ", " ")
        )
    (d / "skel/.config/sheldon/plugins.toml").write_text(toml)
    (d / "skel/.zshrc").write_text(
        ZSHRC.format(name=name, pre=pre, prompt=prompt, post=post)
    )
    for rel, content in (extra_files or {}).items():
        (d / "skel" / rel).parent.mkdir(parents=True, exist_ok=True)
        (d / "skel" / rel).write_text(content)
    setup = d / "setup"
    setup.write_text(
        "#!/usr/bin/env zsh\nsource ${ZSH_SCRIPT:h}/../_common/setup.zsh ${ZSH_SCRIPT:h}\n"
    )
    setup.chmod(setup.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def full(defer=True, swap=None):
    blocks = []
    for step, build in STEPS:
        block = build(defer)
        if swap and step in swap:
            block = swap[step](defer)
        blocks.append(block)
    return blocks


def main():
    for d in CONFIGS.glob("ladder-*"):
        shutil.rmtree(d)
    for d in CONFIGS.glob("alt-*"):
        shutil.rmtree(d)
    names = ["none"] + [s for s, _ in STEPS]
    for mode in ("sync", "defer"):
        defer = mode == "defer"
        for i, step in enumerate(names):
            write(
                f"ladder-{mode}-{i:02d}-{step}", [b(defer) for _, b in STEPS[:i]], defer
            )

    p10k = (REPO / "home/dot_p10k.zsh").read_text()
    alts = {
        "alt-zsh-z": dict(
            blocks=full(swap={"zoxide": lambda d: gh("zsh-z", "agkozak/zsh-z", d)})
        ),
        "alt-z-lua": dict(
            blocks=full(swap={"zoxide": lambda d: gh("z-lua", "skywind3000/z.lua", d)})
        ),
        "alt-zsh-syntax-highlighting": dict(
            blocks=full(
                swap={
                    "fsh": lambda d: gh(
                        "zsh-syntax-highlighting",
                        "zsh-users/zsh-syntax-highlighting",
                        d,
                    )
                }
            )
        ),
        "alt-p10k": dict(
            blocks=full(),
            pre=P10K_PRE,
            prompt="",
            post="source ~/.p10k.zsh\n",
            extra_files={".p10k.zsh": p10k},
        ),
        "alt-atuin": dict(
            blocks=full(
                swap={
                    "zoxide": lambda d: STEPS[4][1](d)
                    + "\n"
                    + inline(
                        "atuin",
                        "spike_cache_eval atuin atuin init zsh --disable-up-arrow",
                        d,
                    )
                }
            )
        ),
        "alt-compinit-uncached": dict(
            blocks=full(
                swap={
                    "compinit": lambda d: inline(
                        "compinit", "autoload -Uz compinit; compinit", d
                    )
                }
            )
        ),
        "alt-zsh-defer-defaults": dict(blocks=full(), opts=""),
        "alt-mise-activate": dict(
            blocks=full(), pre=MISE_ENV + 'eval "$(mise activate zsh)"\n'
        ),
        "alt-mise-shims": dict(
            blocks=full(), pre=MISE_ENV + "path=(/opt/mise/shims $path)\n"
        ),
    }
    # p10k is loaded synchronously (it must draw the prompt), right after zsh-defer
    alts["alt-p10k"]["blocks"] = [
        gh("powerlevel10k", "romkatv/powerlevel10k", False)
    ] + alts["alt-p10k"]["blocks"]
    for name, kw in alts.items():
        write(name, kw.pop("blocks"), True, **kw)
    print("\n".join(sorted(p.name for p in CONFIGS.glob("ladder-*")) + sorted(alts)))


if __name__ == "__main__":
    main()
