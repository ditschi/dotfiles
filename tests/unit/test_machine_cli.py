def test_zsh_completion_registers_machine():
    # Completion is generated by Click from the real command tree (no more
    # hand-duplicated choice lists), so the static script just registers the
    # callback — it doesn't embed profile/feature names. See the dynamic test
    # below for proof that tab-completion actually resolves real subcommands.
    result = subprocess.run(
        ["python3", str(MACHINE), "completion", "zsh"],
        check=True,
        capture_output=True,
        text=True,
    )
    assert "#compdef machine" in result.stdout
    assert "compdef _machine_completion machine" in result.stdout


